/* global $3Dmol, webglAvailable, waitFor3Dmol */
/**
 * Hydrogen orbitals + spherical coordinates (interactive widget)
 *
 * Usage in Markdown:
 *   <div class="hydrogen3d"></div>
 */

function clamp01(x) {
  return Math.max(0, Math.min(1, x));
}

function degToRad(d) {
  return (d * Math.PI) / 180;
}

function factorial(n) {
  if (n < 0) return NaN;
  let out = 1;
  for (let i = 2; i <= n; i++) out *= i;
  return out;
}

function doubleFactorial(n) {
  if (n <= 0) return 1;
  let out = 1;
  for (let k = n; k >= 2; k -= 2) out *= k;
  return out;
}

function assocLegendreP(l, m, x) {
  // m >= 0
  const mm = Math.abs(m);
  if (l < mm) return 0;

  // P_m^m(x) = (-1)^m (2m-1)!! (1-x^2)^{m/2}
  let pmm = 1;
  if (mm > 0) {
    const somx2 = Math.sqrt(Math.max(0, (1 - x) * (1 + x)));
    pmm = Math.pow(-1, mm) * doubleFactorial(2 * mm - 1) * Math.pow(somx2, mm);
  }
  if (l === mm) return pmm;

  // P_{m+1}^m(x) = x (2m+1) P_m^m(x)
  let pmmp1 = x * (2 * mm + 1) * pmm;
  if (l === mm + 1) return pmmp1;

  // upward recurrence:
  // P_l^m(x)=((2l-1)x P_{l-1}^m - (l+m-1) P_{l-2}^m)/(l-m)
  let pll = 0;
  let pprev = pmm;
  let pcurr = pmmp1;
  for (let ll = mm + 2; ll <= l; ll++) {
    pll = ((2 * ll - 1) * x * pcurr - (ll + mm - 1) * pprev) / (ll - mm);
    pprev = pcurr;
    pcurr = pll;
  }
  return pcurr;
}

function realSphericalHarmonicY(l, m, theta, phi) {
  // "Real" spherical harmonics:
  // m = 0: Y_l^0
  // m > 0: sqrt(2) Re(Y_l^m) = sqrt(2) N P_l^m(cosθ) cos(mφ)
  // m < 0: sqrt(2) Im(Y_l^{|m|}) = sqrt(2) N P_l^{|m|}(cosθ) sin(|m|φ)
  const x = Math.cos(theta);
  const mm = Math.abs(m);
  const P = assocLegendreP(l, mm, x);
  const N = Math.sqrt(((2 * l + 1) / (4 * Math.PI)) * (factorial(l - mm) / factorial(l + mm)));

  if (m === 0) return N * P;
  if (m > 0) return Math.SQRT2 * N * P * Math.cos(mm * phi);
  return Math.SQRT2 * N * P * Math.sin(mm * phi);
}

function laguerreL(k, alpha, x) {
  // Generalized Laguerre polynomial L_k^alpha(x) via recurrence.
  if (k === 0) return 1;
  if (k === 1) return 1 + alpha - x;
  let Lkm2 = 1;
  let Lkm1 = 1 + alpha - x;
  let Lk = 0;
  for (let n = 2; n <= k; n++) {
    Lk = (((2 * n - 1 + alpha - x) * Lkm1) - ((n - 1 + alpha) * Lkm2)) / n;
    Lkm2 = Lkm1;
    Lkm1 = Lk;
  }
  return Lkm1;
}

function radialR(n, l, r) {
  // Normalized hydrogen radial function in atomic units (a0=1).
  // rho = 2r/n
  const k = n - l - 1;
  if (k < 0) return 0;
  const rho = (2 * r) / n;
  const norm = Math.sqrt(Math.pow(2 / n, 3) * (factorial(k) / (2 * n * factorial(n + l))));
  const L = laguerreL(k, 2 * l + 1, rho);
  return norm * Math.exp(-rho / 2) * Math.pow(rho, l) * L;
}

function orbitalValue({ n, l, m }, { x, y, z }, mode) {
  const r = Math.sqrt(x * x + y * y + z * z);
  if (r < 1e-12) {
    // theta, phi undefined at origin; take limiting behavior.
    if (l === 0) {
      const R0 = radialR(n, l, 0);
      const Y0 = realSphericalHarmonicY(0, 0, 0, 0);
      const psi0 = R0 * Y0;
      return mode === "prob" ? psi0 * psi0 : psi0;
    }
    return 0;
  }

  const theta = Math.acos(z / r);
  const phi = Math.atan2(y, x) < 0 ? Math.atan2(y, x) + 2 * Math.PI : Math.atan2(y, x);
  const Y = realSphericalHarmonicY(l, m, theta, phi);

  if (mode === "angular") {
    // Put angular function on a thin shell around r ≈ 1 (in a0).
    const sigma = 0.18;
    const shell = Math.exp(-((r - 1.0) * (r - 1.0)) / (2 * sigma * sigma));
    return Y * shell;
  }

  const R = radialR(n, l, r);
  const psi = R * Y;
  return mode === "prob" ? psi * psi : psi;
}

function toCubeText({ origin, nx, ny, nz, dx, dy, dz, values }) {
  // Minimal Gaussian cube format: natoms=0.
  // Data ordering: z fastest, then y, then x.
  const lines = [];
  lines.push("CUBE file generated by hydrogen-spherical.js");
  lines.push("Volumetric data: hydrogen orbital scalar field");
  lines.push(`0 ${origin.x.toFixed(6)} ${origin.y.toFixed(6)} ${origin.z.toFixed(6)}`);
  lines.push(`${nx} ${dx.toFixed(6)} 0.000000 0.000000`);
  lines.push(`${ny} 0.000000 ${dy.toFixed(6)} 0.000000`);
  lines.push(`${nz} 0.000000 0.000000 ${dz.toFixed(6)}`);

  let col = 0;
  let row = [];
  for (let i = 0; i < values.length; i++) {
    row.push(values[i].toExponential(5));
    col++;
    if (col === 6) {
      lines.push(row.join(" "));
      row = [];
      col = 0;
    }
  }
  if (row.length) lines.push(row.join(" "));
  return lines.join("\n") + "\n";
}

function buildOrbitalCube({ orbital, mode, rMax, grid }) {
  const n = orbital.n;
  const l = orbital.l;
  const m = orbital.m;

  const nx = grid;
  const ny = grid;
  const nz = grid;
  const origin = { x: -rMax, y: -rMax, z: -rMax };
  const dx = (2 * rMax) / (nx - 1);
  const dy = (2 * rMax) / (ny - 1);
  const dz = (2 * rMax) / (nz - 1);

  const values = new Float32Array(nx * ny * nz);
  let idx = 0;
  for (let ix = 0; ix < nx; ix++) {
    const x = origin.x + ix * dx;
    for (let iy = 0; iy < ny; iy++) {
      const y = origin.y + iy * dy;
      for (let iz = 0; iz < nz; iz++) {
        const z = origin.z + iz * dz;
        values[idx++] = orbitalValue({ n, l, m }, { x, y, z }, mode);
      }
    }
  }

  return toCubeText({
    origin,
    nx,
    ny,
    nz,
    dx,
    dy,
    dz,
    values,
  });
}

function parseOrbitalKey(key) {
  // Supported: 1s, 2s, 2p-1, 2p0, 2p1, 3d-2..2
  const k = String(key || "").trim().toLowerCase();
  if (k === "1s") return { n: 1, l: 0, m: 0, label: "1s (n=1,l=0,m=0)" };
  if (k === "2s") return { n: 2, l: 0, m: 0, label: "2s (n=2,l=0,m=0)" };
  if (k === "2p-1") return { n: 2, l: 1, m: -1, label: "2p (m=-1)" };
  if (k === "2p0") return { n: 2, l: 1, m: 0, label: "2p (m=0)" };
  if (k === "2p1") return { n: 2, l: 1, m: 1, label: "2p (m=+1)" };
  if (k === "3d-2") return { n: 3, l: 2, m: -2, label: "3d (m=-2)" };
  if (k === "3d-1") return { n: 3, l: 2, m: -1, label: "3d (m=-1)" };
  if (k === "3d0") return { n: 3, l: 2, m: 0, label: "3d (m=0)" };
  if (k === "3d1") return { n: 3, l: 2, m: 1, label: "3d (m=+1)" };
  if (k === "3d2") return { n: 3, l: 2, m: 2, label: "3d (m=+2)" };
  return { n: 2, l: 1, m: 0, label: "2p (m=0)" };
}

function cartFromSpherical({ r, thetaDeg, phiDeg }) {
  const theta = degToRad(thetaDeg);
  const phi = degToRad(phiDeg);
  const x = r * Math.sin(theta) * Math.cos(phi);
  const y = r * Math.sin(theta) * Math.sin(phi);
  const z = r * Math.cos(theta);
  return { x, y, z };
}

function addAxes(viewer, scale) {
  // X red, Y green, Z blue
  const o = { x: 0, y: 0, z: 0 };
  viewer.addLine({ start: o, end: { x: scale, y: 0, z: 0 }, color: "#cc3333", opacity: 0.9 });
  viewer.addLine({ start: o, end: { x: 0, y: scale, z: 0 }, color: "#2f9e44", opacity: 0.9 });
  viewer.addLine({ start: o, end: { x: 0, y: 0, z: scale }, color: "#2b6cb0", opacity: 0.9 });
  viewer.addLabel("+x", { position: { x: scale, y: 0, z: 0 }, fontSize: 10, backgroundColor: "rgba(255,255,255,0.65)" });
  viewer.addLabel("+y", { position: { x: 0, y: scale, z: 0 }, fontSize: 10, backgroundColor: "rgba(255,255,255,0.65)" });
  viewer.addLabel("+z", { position: { x: 0, y: 0, z: scale }, fontSize: 10, backgroundColor: "rgba(255,255,255,0.65)" });
}

function addGlowPoint(viewer, pos, label) {
  // Fake “glow” with 2 spheres + label.
  viewer.addSphere({ center: pos, radius: 0.12, color: "#ffcc00", opacity: 1.0 });
  viewer.addSphere({ center: pos, radius: 0.26, color: "#ffcc00", opacity: 0.28 });
  viewer.addLabel(label, {
    position: { x: pos.x + 0.2, y: pos.y + 0.2, z: pos.z + 0.2 },
    fontSize: 10,
    fontColor: "#111",
    backgroundColor: "rgba(255,255,255,0.75)",
    borderColor: "rgba(0,0,0,0.2)",
    borderThickness: 0.8,
    inFront: true,
    showBackground: true,
  });
}

function addPhiPlane(viewer, { phiDeg, rMax, density = 10 }) {
  // constant φ: a half-plane through the z-axis.
  const phi = degToRad(phiDeg);
  const color = "#8b5cf6";

  // Rays (constant θ)
  for (let i = 0; i <= density; i++) {
    const theta = (i * Math.PI) / density;
    const end = {
      x: rMax * Math.sin(theta) * Math.cos(phi),
      y: rMax * Math.sin(theta) * Math.sin(phi),
      z: rMax * Math.cos(theta),
    };
    viewer.addLine({ start: { x: 0, y: 0, z: 0 }, end, color, opacity: 0.25 });
  }

  // Arcs (constant r)
  const seg = 48;
  for (let j = 1; j <= Math.max(3, Math.floor(density / 2)); j++) {
    const r = (j * rMax) / Math.max(3, Math.floor(density / 2));
    let prev = null;
    for (let s = 0; s <= seg; s++) {
      const theta = (s * Math.PI) / seg;
      const p = {
        x: r * Math.sin(theta) * Math.cos(phi),
        y: r * Math.sin(theta) * Math.sin(phi),
        z: r * Math.cos(theta),
      };
      if (prev) viewer.addLine({ start: prev, end: p, color, opacity: 0.18 });
      prev = p;
    }
  }

  viewer.addLabel(`φ = ${phiDeg}° (half-plane)`, {
    position: { x: 0.15 * rMax * Math.cos(phi), y: 0.15 * rMax * Math.sin(phi), z: 0.9 * rMax },
    fontSize: 10,
    backgroundColor: "rgba(255,255,255,0.65)",
  });
}

function addThetaCone(viewer, { thetaDeg, rMax, density = 10 }) {
  // constant θ: a cone around the z-axis.
  const theta = degToRad(thetaDeg);
  const color = "#06b6d4";

  // Generator lines (constant φ)
  const rays = 18;
  for (let i = 0; i < rays; i++) {
    const phi = (i * 2 * Math.PI) / rays;
    const end = {
      x: rMax * Math.sin(theta) * Math.cos(phi),
      y: rMax * Math.sin(theta) * Math.sin(phi),
      z: rMax * Math.cos(theta),
    };
    viewer.addLine({ start: { x: 0, y: 0, z: 0 }, end, color, opacity: 0.22 });
  }

  // Rings at increasing r
  const seg = 64;
  for (let j = 1; j <= Math.max(3, Math.floor(density / 2)); j++) {
    const r = (j * rMax) / Math.max(3, Math.floor(density / 2));
    const rr = r * Math.sin(theta);
    const zz = r * Math.cos(theta);
    let prev = null;
    for (let s = 0; s <= seg; s++) {
      const phi = (s * 2 * Math.PI) / seg;
      const p = { x: rr * Math.cos(phi), y: rr * Math.sin(phi), z: zz };
      if (prev) viewer.addLine({ start: prev, end: p, color, opacity: 0.16 });
      prev = p;
    }
  }

  viewer.addLabel(`θ = ${thetaDeg}° (cone)`, {
    position: { x: 0.0, y: 0.0, z: rMax * Math.cos(theta) },
    fontSize: 10,
    backgroundColor: "rgba(255,255,255,0.65)",
  });
}


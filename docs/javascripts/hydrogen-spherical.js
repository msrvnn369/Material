async function renderHydrogen3D(container) {
  container.style.width = container.style.width || "100%";

  if (!webglAvailable()) {
    container.innerText = "Interactive 3D model unavailable (WebGL disabled/not supported).";
    return;
  }

  await waitFor3Dmol();
  const ui = createControls(container);

  let viewer;
  try {
    viewer = $3Dmol.createViewer(ui.view, { backgroundColor: "white" });
  } catch (e) {
    container.innerText = `3D viewer init failed: ${e?.message || String(e)}`;
    return;
  }

  const state = {
    orbitalKey: ui.els.orbital.value,
    mode: ui.els.mode.value,
    rMax: parseFloat(ui.els.rMax.value),
    grid: parseInt(ui.els.grid.value, 10),
    iso: parseFloat(ui.els.iso.value),
    point: {
      r: parseFloat(ui.els.pr.value),
      thetaDeg: parseFloat(ui.els.ptheta.value),
      phiDeg: parseFloat(ui.els.pphi.value),
    },
    overlays: {
      showPhiPlane: ui.els.showPhiPlane.checked,
      phiPlane: parseFloat(ui.els.phiPlane.value),
      showThetaCone: ui.els.showThetaCone.checked,
      thetaCone: parseFloat(ui.els.thetaCone.value),
      showAxes: ui.els.showAxes.checked,
    },
  };

  function syncLabels() {
    ui.els.rMaxLabel.textContent = String(parseFloat(ui.els.rMax.value));
    ui.els.gridLabel.textContent = String(parseInt(ui.els.grid.value, 10));
    ui.els.isoLabel.textContent = String(parseFloat(ui.els.iso.value).toFixed(3).replace(/0+$/, "").replace(/\.$/, ""));
  }

  function readStateFromUI() {
    state.orbitalKey = ui.els.orbital.value;
    state.mode = ui.els.mode.value;
    state.rMax = parseFloat(ui.els.rMax.value);
    state.grid = parseInt(ui.els.grid.value, 10);
    state.iso = parseFloat(ui.els.iso.value);

    state.point.r = parseFloat(ui.els.pr.value);
    state.point.thetaDeg = parseFloat(ui.els.ptheta.value);
    state.point.phiDeg = parseFloat(ui.els.pphi.value);

    state.overlays.showPhiPlane = ui.els.showPhiPlane.checked;
    state.overlays.phiPlane = parseFloat(ui.els.phiPlane.value);
    state.overlays.showThetaCone = ui.els.showThetaCone.checked;
    state.overlays.thetaCone = parseFloat(ui.els.thetaCone.value);
    state.overlays.showAxes = ui.els.showAxes.checked;
  }

  function clearAndRedrawOverlays() {
    // Keep the volume surface; just clear shapes/labels by re-creating viewer shapes.
    // 3Dmol doesn't provide a perfect "clear only shapes" API in all builds, so we
    // rebuild the full scene (fast enough at this scale).
    rerenderAll(false);
  }

  function addOverlays() {
    const rMax = state.rMax;
    const axisScale = Math.min(4.5, 0.75 * rMax);

    if (state.overlays.showAxes) addAxes(viewer, axisScale);

    const pos = cartFromSpherical(state.point);
    addGlowPoint(
      viewer,
      pos,
      `point: r=${state.point.r}, θ=${state.point.thetaDeg}°, φ=${state.point.phiDeg}°`,
    );

    if (state.overlays.showPhiPlane) addPhiPlane(viewer, { phiDeg: state.overlays.phiPlane, rMax, density: 12 });
    if (state.overlays.showThetaCone) addThetaCone(viewer, { thetaDeg: state.overlays.thetaCone, rMax, density: 12 });
  }

  function rerenderAll(regenVolume) {
    // If regenVolume=false, we still rebuild everything because it's the most reliable
    // across 3Dmol builds. (The heavy step is generating the cube, which we can skip.)
    const keepCamera = viewer.getView();

    viewer.clear();

    // Volume surfaces
    if (regenVolume || !state._cachedCubeText) {
      const orbital = parseOrbitalKey(state.orbitalKey);
      const cubeText = buildOrbitalCube({ orbital, mode: state.mode, rMax: state.rMax, grid: state.grid });
      state._cachedCubeText = cubeText;
    }

    const vol = new $3Dmol.VolumeData(state._cachedCubeText, "cube");

    // Colors & opacity tuned for readability
    if (state.mode === "prob") {
      viewer.addIsosurface(vol, {
        isoval: state.iso,
        color: "#0ea5e9",
        opacity: clamp01(0.55),
        smoothness: 5,
      });
    } else {
      viewer.addIsosurface(vol, {
        isoval: state.iso,
        color: "#ef4444",
        opacity: clamp01(0.55),
        smoothness: 5,
      });
      viewer.addIsosurface(vol, {
        isoval: -state.iso,
        color: "#2563eb",
        opacity: clamp01(0.55),
        smoothness: 5,
      });
    }

    addOverlays();

    viewer.setView(keepCamera);
    viewer.render();
  }

  function resetCamera() {
    viewer.zoomTo();
    viewer.render();
  }

  // Initial render
  syncLabels();
  readStateFromUI();
  rerenderAll(true);
  resetCamera();

  // Wire events
  ui.els.rMax.addEventListener("input", () => {
    syncLabels();
  });
  ui.els.grid.addEventListener("input", () => {
    syncLabels();
  });
  ui.els.iso.addEventListener("input", () => {
    syncLabels();
  });

  // Lightweight overlay updates (no cube regen)
  const overlayChange = () => {
    syncLabels();
    readStateFromUI();
    clearAndRedrawOverlays();
  };

  ui.els.pr.addEventListener("change", overlayChange);
  ui.els.ptheta.addEventListener("change", overlayChange);
  ui.els.pphi.addEventListener("change", overlayChange);
  ui.els.showPhiPlane.addEventListener("change", overlayChange);
  ui.els.phiPlane.addEventListener("change", overlayChange);
  ui.els.showThetaCone.addEventListener("change", overlayChange);
  ui.els.thetaCone.addEventListener("change", overlayChange);
  ui.els.showAxes.addEventListener("change", overlayChange);

  // Volume-affecting changes
  const volumeChange = () => {
    syncLabels();
    readStateFromUI();
    state._cachedCubeText = null;
    rerenderAll(true);
    resetCamera();
  };
  ui.els.orbital.addEventListener("change", volumeChange);
  ui.els.mode.addEventListener("change", volumeChange);

  ui.els.rerender.addEventListener("click", () => {
    syncLabels();
    readStateFromUI();
    state._cachedCubeText = null;
    rerenderAll(true);
  });
  ui.els.reset.addEventListener("click", resetCamera);

  // Smooth isovalue updates without cube regen
  ui.els.iso.addEventListener("change", () => {
    syncLabels();
    readStateFromUI();
    rerenderAll(false);
  });

  // rMax/grid changes require volume regen (but don’t do it on every slider tick)
  let volTimer = null;
  const scheduleVol = () => {
    syncLabels();
    if (volTimer) clearTimeout(volTimer);
    volTimer = setTimeout(() => {
      readStateFromUI();
      state._cachedCubeText = null;
      rerenderAll(true);
      viewer.render();
    }, 250);
  };
  ui.els.rMax.addEventListener("change", scheduleVol);
  ui.els.grid.addEventListener("change", scheduleVol);
}

function renderAllHydrogen3D() {
  document.querySelectorAll(".hydrogen3d").forEach((el) => {
    if (el.getAttribute("data-rendered") === "true") return;
    if (el.getAttribute("data-rendering") === "true") return;
    el.setAttribute("data-rendering", "true");
    el.innerText = "Loading interactive hydrogen viewer…";
    renderHydrogen3D(el)
      .catch((err) => {
        el.innerText = `Hydrogen viewer error: ${err?.message || String(err)}`;
      })
      .finally(() => {
        el.setAttribute("data-rendered", "true");
        el.setAttribute("data-rendering", "false");
      });
  });
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", renderAllHydrogen3D);
} else {
  renderAllHydrogen3D();
}
document.addEventListener("navigation:complete", renderAllHydrogen3D);
if (window.document$ && typeof window.document$.subscribe === "function") {
  window.document$.subscribe(() => renderAllHydrogen3D());
}

